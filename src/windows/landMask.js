let bits = null
function decode() {
  const bin = atob(B64)
  bits = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) bits[i] = bin.charCodeAt(i)
  return bits
}

/** True if the given longitude/latitude (degrees) is on land. */
export function isLand(lon, lat) {
  const b = bits || decode()
  const x = Math.min(MASK_W - 1, Math.max(0, Math.floor(((lon + 180) / 360) * MASK_W)))
  const y = Math.min(MASK_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * MASK_H)))
  const i = y * MASK_W + x
  return (b[i >> 3] & (1 << (i & 7))) !== 0
}
